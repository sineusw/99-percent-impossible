import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),library=require('../cast-lines.js');
const hash=text=>{let h=0x811c9dc5;for(let i=0;i<text.length;i++){h^=text.charCodeAt(i);h=Math.imul(h,0x01000193)}return(h>>>0).toString(16).padStart(8,'0')};
const available={},missing=[];
for(const character of ['daisy','mick']){
 available[character]=[];
 for(const [category,lines] of Object.entries(library[character])){
  const shipped=lines.filter(line=>{
   const file=new URL(`../assets/${character}-audio/${hash(line.text.trim())}.mp3`,import.meta.url);
   if(fs.existsSync(file)&&fs.statSync(file).size>0)return true;
   missing.push(line.id);return false;
  });
  if(!shipped.length)throw new Error(`No shipped audio for ${character}/${category}`);
  available[character].push(...shipped.map(line=>line.id));
 }
}
const output='/* Generated by scripts/check-cast-audio.mjs --write. Only shipped phrase IDs. */\nwindow.N99CastAudioAvailable='+JSON.stringify(available)+';\n';
const target=new URL('../cast-audio-available.js',import.meta.url);
if(process.argv.includes('--write'))fs.writeFileSync(target,output);
else if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw new Error('Cast audio availability is stale; run node scripts/check-cast-audio.mjs --write');
console.log(`Cast assets verified: ${available.daisy.length} Daisy, ${available.mick.length} Mick; ${missing.length} unavailable variants excluded.`);
